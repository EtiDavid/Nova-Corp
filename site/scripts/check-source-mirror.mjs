import {createHash} from "node:crypto";
import {existsSync,readFileSync,readdirSync} from "node:fs";
import {resolve,join,relative} from "node:path";
const repoDocs=resolve("../docs"),dist=resolve("dist"),manifestFile=resolve("dist/references/manifest.json");
if(!existsSync(manifestFile))throw Error("Canonical public Markdown source manifest not generated by build");
const m=JSON.parse(readFileSync(manifestFile,"utf8"));
const errors=[],ids=new Set();
if(m.docsCount<140)errors.push("Document mirror incomplete: "+m.docsCount);
if(m.docsCount!==m.documents.length)errors.push("Manifest document count mismatch");
function scan(p){return readdirSync(p,{withFileTypes:true}).flatMap(e=>e.isDirectory()?scan(join(p,e.name)):e.name.endsWith(".md")?[join(p,e.name)]:[]);}
const sourceFiles=scan(repoDocs);
if(sourceFiles.length!==m.docsCount)errors.push("Source docs count "+sourceFiles.length+" differs from published "+m.docsCount);
for(const doc of m.documents){
 if(ids.has(doc.id))errors.push("Duplicate source document id: "+doc.id);
 ids.add(doc.id);
 const original=resolve("../"+doc.source);
 if(!original.startsWith(repoDocs+"/")||!existsSync(original)){errors.push("Absent canonical source: "+doc.source);continue;}
 const raw=readFileSync(original);
 const expected=createHash("sha256").update(raw).digest("hex");
 if(expected!==doc.sha256||raw.length!==doc.bytes)errors.push("Source hash or size mismatch: "+doc.source);
 const page=resolve(dist,"reference",doc.id,"index.html");
 if(!existsSync(page))errors.push("Missing source article route: "+doc.id);
 else if(!readFileSync(page,"utf8").includes('source-document'))errors.push("Missing full rendered Markdown area: "+doc.id);
}
const expectedPages={
 "systems/nova-fw01/index.html":[
  "eight interfaces","five VLANs","17 filter rules","one active WireGuard",
  "six DHCP scopes","Original engineering records"
 ],
 "systems/nova-dc01/index.html":["Related tests and incidents","Domain Controller","directory","Technical Profile"],
 "systems/nova-files01/index.html":["Technical profile","Backup","shared"],
 "policies/domain-password/index.html":["Complete original Group Policy explanation","Password"],
 "network/zones/client/index.html":["Complete network-zone documentation","CLIENT"],
 "network/rules/1795199640/index.html":["Full documented rule explanation","BLOCK"],
 "files/shares/it/index.html":["What is the IT folder?","/reference/explore/files/it/","Engineering journals"],
 "reference/explore/systems/NOVA-FW01/index.html":["eight interfaces","Stateful","Original engineering source"]
};
for(const [page,phrases] of Object.entries(expectedPages)){
 const file=join(dist,page);
 if(!existsSync(file)){errors.push("Missing deep technical page "+page);continue;}
 const contents=readFileSync(file,"utf8");
 for(const phrase of phrases){if(!contents.toLowerCase().includes(phrase.toLowerCase()))errors.push("Missing original source detail '"+phrase+"' on "+page);}
}
if(errors.length){console.error(errors.slice(0,90).join("\n"));process.exit(1);}
console.log("Source-faithful site parity PASS: "+ids.size+" original public Markdown sources, SHA-256 equal; all standalone article routes; deep in-site pfSense, DC, file-share, GPO and firewall-rule content.");
